create or replace function public.current_role()
returns text language sql stable security definer set search_path=public
as $$ select role from public.profiles where id=auth.uid() and active=true limit 1 $$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select public.current_role()='ADMINISTRADOR' $$;

create or replace function public.can_manage_school()
returns boolean language sql stable security definer set search_path=public
as $$ select public.current_role() in ('ADMINISTRADOR','DIRECTOR','SECRETARIA') $$;

