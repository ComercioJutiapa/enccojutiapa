select c.id,v.n,v.name,case when v.n=2 then 'ABIERTO' else 'CERRADO' end
from public.school_cycles c cross join (values(1,'I Bimestre'),(2,'II Bimestre'),(3,'III Bimestre'),(4,'IV Bimestre')) v(n,name)
