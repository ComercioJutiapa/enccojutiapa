-- Plataforma Escuela Nacional de Ciencias Comerciales
-- Supabase/PostgreSQL
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('ADMINISTRADOR','DIRECTOR','SECRETARIA','DOCENTE')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.school_settings (
  id bigint generated by default as identity primary key,
  institution_name text not null default 'Escuela Nacional de Ciencias Comerciales',
  max_grade numeric(5,2) not null default 100 check (max_grade > 0),
  bimesters_count integer not null default 4 check (bimesters_count between 1 and 6),
  created_at timestamptz not null default now()
);

create table if not exists public.school_cycles (
  id bigint generated by default as identity primary key,
  year integer not null unique,
  name text not null,
  start_date date,
  end_date date,
  status text not null default 'ACTIVO' check (status in ('ACTIVO','CERRADO'))
);

create table if not exists public.grades (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true
);

create table if not exists public.sections (
  id bigint generated by default as identity primary key,
  grade_id bigint not null references public.grades(id) on delete restrict,
  name text not null,
  active boolean not null default true,
  unique(grade_id,name)
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  code text unique,
  name text not null,
  active boolean not null default true
);

create table if not exists public.pensum (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references public.school_cycles(id) on delete cascade,
  grade_id bigint not null references public.grades(id) on delete restrict,
  subject_id bigint not null references public.subjects(id) on delete restrict,
  weekly_hours integer not null default 4 check (weekly_hours > 0),
  mandatory boolean not null default true,
  unique(cycle_id,grade_id,subject_id)
);

create table if not exists public.teachers (
  id bigint generated by default as identity primary key,
  profile_id uuid references public.profiles(id) on delete set null,
  code text not null unique,
  full_name text not null,
  email text,
  phone text,
  renglon text not null default '011' check (renglon in ('011','021')),
  gender text not null default 'Masculino' check (gender in ('Masculino','Femenino')),
  status text not null default 'ACTIVO' check (status in ('ACTIVO','INACTIVO'))
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  code text not null unique,
  full_name text not null,
  birth_date date,
  phone text,
  address text,
  responsible_name text,
  responsible_phone text,
  photo_path text,
  status text not null default 'ACTIVO' check (status in ('ACTIVO','INACTIVO')),
  created_at timestamptz not null default now()
);

create table if not exists public.enrollments (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete restrict,
  cycle_id bigint not null references public.school_cycles(id) on delete restrict,
  grade_id bigint not null references public.grades(id) on delete restrict,
  section_id bigint not null references public.sections(id) on delete restrict,
  enrollment_status text not null default 'ACTIVA' check (enrollment_status in ('ACTIVA','RETIRADA','FINALIZADA')),
  withdrawal_reason text,
  withdrawal_delivered_to text,
  withdrawal_delivery_date date,
  created_at timestamptz not null default now(),
  unique(student_id,cycle_id)
);

create table if not exists public.teacher_assignments (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references public.school_cycles(id) on delete cascade,
  teacher_id bigint not null references public.teachers(id) on delete restrict,
  grade_id bigint not null references public.grades(id) on delete restrict,
  section_id bigint not null references public.sections(id) on delete restrict,
  subject_id bigint not null references public.subjects(id) on delete restrict,
  active boolean not null default true,
  unique(cycle_id,teacher_id,grade_id,section_id,subject_id)
);

create table if not exists public.bimesters (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references public.school_cycles(id) on delete cascade,
  number integer not null check (number > 0),
  name text not null,
  status text not null default 'CERRADO' check (status in ('ABIERTO','CERRADO')),
  unique(cycle_id,number)
);

create table if not exists public.grades_records (
  id bigint generated by default as identity primary key,
  enrollment_id bigint not null references public.enrollments(id) on delete cascade,
  assignment_id bigint not null references public.teacher_assignments(id) on delete cascade,
  bimester_id bigint not null references public.bimesters(id) on delete restrict,
  zone numeric(5,2) not null default 0 check (zone >= 0),
  evaluation numeric(5,2) not null default 0 check (evaluation >= 0),
  total numeric(5,2) generated always as (zone + evaluation) stored,
  created_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique(enrollment_id,assignment_id,bimester_id)
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  enrollment_id bigint not null references public.enrollments(id) on delete cascade,
  assignment_id bigint not null references public.teacher_assignments(id) on delete cascade,
  attendance_date date not null,
  status text not null check (status in ('PRESENTE','AUSENTE','TARDANZA','JUSTIFICADA')),
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  unique(enrollment_id,assignment_id,attendance_date)
);

create table if not exists public.disciplinary_reports (
  id bigint generated by default as identity primary key,
  enrollment_id bigint not null references public.enrollments(id) on delete cascade,
  teacher_id bigint references public.teachers(id) on delete set null,
  report_date date not null default current_date,
  report_type text not null default 'DISCIPLINARIO',
  description text not null,
  actions_taken text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.honor_roll (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references public.school_cycles(id) on delete cascade,
  enrollment_id bigint not null references public.enrollments(id) on delete cascade,
  average numeric(6,2) not null,
  position integer,
  calculated_at timestamptz not null default now(),
  unique(cycle_id,enrollment_id)
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  table_name text not null,
  action text not null,
  record_id text,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_enrollments_cycle_grade_section on public.enrollments(cycle_id,grade_id,section_id);
create index if not exists idx_grades_records_bimester on public.grades_records(bimester_id);
