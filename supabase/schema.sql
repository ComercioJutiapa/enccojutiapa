on conflict(cycle_id,number) do nothing;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  insert into public.profiles(id,full_name,role)
  values(new.id,coalesce(new.raw_user_meta_data->>'full_name',new.email),'DOCENTE')
  on conflict(id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.validate_grade_total()
returns trigger language plpgsql
as $$
begin
  if new.zone + new.evaluation > (select max_grade from public.school_settings order by id limit 1) then
    raise exception 'La calificación total no puede superar el máximo configurado.';
  end if;
  return new;
end $$;

drop trigger if exists trg_validate_grade_total on public.grades_records;
create trigger trg_validate_grade_total
before insert or update on public.grades_records
for each row execute procedure public.validate_grade_total();


